-- ====================================================================
-- مخطط قاعدة بيانات مطعم حضرموت اليمني - الناصرية (Supabase Schema)
-- ====================================================================

-- 1. جدول التصنيفات (Categories)
CREATE TABLE IF NOT EXISTS public.categories (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  sub TEXT NOT NULL,
  image TEXT NOT NULL,
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. جدول أطباق المنيو (Dishes)
CREATE TABLE IF NOT EXISTS public.dishes (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  category TEXT NOT NULL REFERENCES public.categories(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  title TEXT NOT NULL,
  sub TEXT NOT NULL,
  price INT NOT NULL CHECK (price >= 0),
  image TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  available BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. جدول مناطق التوصيل وأجورها (Delivery Areas)
CREATE TABLE IF NOT EXISTS public.delivery_areas (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  fee INT NOT NULL CHECK (fee >= 0),
  sort_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. جدول إعدادات وبيانات المطعم العامة (Restaurant Settings)
CREATE TABLE IF NOT EXISTS public.restaurant_settings (
  key TEXT PRIMARY KEY,
  value JSONB NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. جدول كوبونات الخصم (Discount Coupons)
CREATE TABLE IF NOT EXISTS public.coupons (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code TEXT NOT NULL UNIQUE,
  discount_type TEXT NOT NULL CHECK (discount_type IN ('percent', 'fixed')),
  discount_value INT NOT NULL CHECK (discount_value > 0),
  min_order INT NOT NULL DEFAULT 0 CHECK (min_order >= 0),
  max_uses INT NOT NULL DEFAULT 0 CHECK (max_uses >= 0),
  used_count INT NOT NULL DEFAULT 0 CHECK (used_count >= 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.coupons ADD COLUMN IF NOT EXISTS max_uses INT NOT NULL DEFAULT 0;
ALTER TABLE public.coupons ADD COLUMN IF NOT EXISTS used_count INT NOT NULL DEFAULT 0;

-- سجل استخدام الكوبونات لمنع التكرار لكل جهاز أو رقم هاتف
CREATE TABLE IF NOT EXISTS public.coupon_redemptions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  coupon_id UUID NOT NULL REFERENCES public.coupons(id) ON DELETE CASCADE,
  coupon_code TEXT NOT NULL,
  device_id TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_coupon_redemptions_coupon_device ON public.coupon_redemptions (coupon_id, device_id);
CREATE INDEX IF NOT EXISTS idx_coupon_redemptions_coupon_phone ON public.coupon_redemptions (coupon_id, customer_phone);

-- 6. جدول الطلبات (Orders)
CREATE TABLE IF NOT EXISTS public.orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code TEXT,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  fulfillment TEXT NOT NULL CHECK (fulfillment IN ('delivery', 'pickup')),
  area TEXT,
  address TEXT NOT NULL,
  notes TEXT DEFAULT '',
  items JSONB NOT NULL,
  subtotal INT NOT NULL,
  delivery_fee INT NOT NULL,
  coupon_code TEXT,
  discount_amount INT NOT NULL DEFAULT 0,
  total INT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'preparing', 'out_for_delivery', 'delivered', 'cancelled')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS coupon_code TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS discount_amount INT NOT NULL DEFAULT 0;

